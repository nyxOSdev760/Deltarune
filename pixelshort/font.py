"""Hand-made variable-width pixel font.

Cap height 7, x-height 5, 2 px descenders. Text is drawn with a flat fill
(white or yellow) and a 1 px dark border all the way round.
"""
import numpy as np

_G = {}


def _glyph(ch, *rows, top=0):
    """rows are drawn starting at row `top` of a 9-row cell (7 cap + 2 desc)."""
    w = len(rows[0])
    cell = ["." * w] * 9
    for i, r in enumerate(rows):
        assert len(r) == w, (ch, r)
        cell[top + i] = r
    _G[ch] = cell


