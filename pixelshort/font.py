LINE_H = 11   # 9 cell rows + 2 px leading
SPACING = 1


def text_width(s):
    if not s:
        return 0
    return sum(len(_G.get(c, _G["?"])[0]) for c in s) + SPACING * (len(s) - 1)


def wrap(s, max_w):
    lines, cur = [], ""
    for word in s.split(" "):
        trial = (cur + " " + word) if cur else word
        if text_width(trial) <= max_w:
            cur = trial
        else:
            if cur:
                lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines


def text_mask(s):
    w = max(1, text_width(s))
    m = np.zeros((9, w), dtype=bool)
    x = 0
    for c in s:
        g = _G.get(c, _G["?"])
        for y, row in enumerate(g):
            for i, ch in enumerate(row):
                if ch == "#":
                    m[y, x + i] = True
        x += len(g[0]) + SPACING
    return m


def draw_text(canvas, s, x, y, fill=(255, 255, 255), border=(18, 14, 36)):
    """Draw text with a solid 1 px border (8-connected) around every glyph."""
    m = text_mask(s)
    h, w = m.shape
    pm = np.pad(m, 1)
    b = np.zeros_like(pm)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            b |= np.roll(np.roll(pm, dy, 0), dx, 1)
    for yy in range(h + 2):
        for xx in range(w + 2):
            if pm[yy, xx]:
                canvas.pset(x - 1 + xx, y - 1 + yy, fill)
            elif b[yy, xx]:
                canvas.pset(x - 1 + xx, y - 1 + yy, border)
